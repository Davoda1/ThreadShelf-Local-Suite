import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {ApplicationService} from '../src/core/service.mjs';
const fixturePath=fileURLToPath(new URL('./fixtures/migration-v1.1.1',import.meta.url));
const digest=file=>fs.readFile(file).then(bytes=>createHash('sha256').update(bytes).digest('hex'));
test('2.0 starts an independent archive and preserves old databases and reading bytes',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'tslr-v2-boundary-')),dataDir=path.join(root,'profile');
 await fs.cp(fixturePath,dataDir,{recursive:true});
 await fs.mkdir(path.join(dataDir,'local-storage-v1'));
 await fs.writeFile(path.join(dataDir,'local-storage-v1','current.json'),'prior-version-sentinel');
 const old=['archive.sqlite','search/vectors.sqlite','reading.json','reading.json.bak','window.json','local-storage-v1/current.json'];
 const before=await Promise.all(old.map(file=>digest(path.join(dataDir,file))));
 let service=await new ApplicationService({dataDir}).init();
 t.after(async()=>{await service.shutdown().catch(()=>{});await fs.rm(root,{recursive:true,force:true});});
 assert.equal((await service.handle('files',{mode:'local'})).total,0);
 assert.equal((await service.handle('bootstrap')).settings.language,'hu');
 assert.deepEqual((await service.handle('bootstrap')).reading.bookmarks,[]);
 await service.handle('manager.mutate',{operation:'create',name:'Version Two'});
 await service.handle('manager.mutate',{operation:'clear'});
 await service.shutdown();service=await new ApplicationService({dataDir}).init();
 assert.deepEqual(await Promise.all(old.map(file=>digest(path.join(dataDir,file)))),before);
 assert.ok((await fs.stat(path.join(dataDir,'local-storage-v2','current.json'))).isFile());
 assert.ok((await fs.stat(path.join(dataDir,'reading-v2.json'))).isFile());
});
