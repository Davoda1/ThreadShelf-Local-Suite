/** Rebuild the offline holiday-country map from the preserved IANA snapshot. */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const defaultOutput = path.resolve(here, '../../src/desktop/holiday/src/timezone-countries.mjs');

function usage() {
  console.log('Usage: node scripts/timezone-data/build.mjs [--check] [--output PATH]\n' +
    'Rebuild the bundled offline timezone-to-country map using only preserved inputs.\n' +
    '  --check        Compare generated bytes with the destination; do not write.\n' +
    '  --output PATH  Use another output file, relative to the current directory.\n' +
    '  --help         Show this help.\n' +
    'Default: src/desktop/holiday/src/timezone-countries.mjs');
}

async function main() {
  let output = defaultOutput;
  let check = false;
  const args = process.argv.slice(2);
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--help' || args[i] === '-h') { usage(); return; }
    if (args[i] === '--check') { check = true; continue; }
    if (args[i] === '--output' && args[i + 1]) { output = path.resolve(args[++i]); continue; }
    throw new Error(`Unknown or incomplete argument: ${args[i]}`);
  }

  const manifest = JSON.parse(await readFile(path.join(here, 'provenance.json'), 'utf8'));
  const inputDirectory = path.join(here, manifest.inputDirectory);
  const inputs = {};
  for (const [name, expectedHash] of Object.entries(manifest.sha256)) {
    const bytes = await readFile(path.join(inputDirectory, name));
    const hash = createHash('sha256').update(bytes).digest('hex');
    if (hash !== expectedHash) throw new Error(`Preserved IANA input differs from provenance: ${name}`);
    inputs[name] = bytes.toString('utf8');
  }
  const version = inputs.version.trim();
  if (version !== manifest.version) throw new Error('IANA version differs from provenance');
  const rows = name => inputs[name].split(/\r?\n/).filter(line => line && !line.startsWith('#')).map(line => line.split('\t'));

  // Country-specific original names win, even if their clocks match another country.
  const zones = new Map(rows('zone.tab').map(row => [row[2], row[0]]));
  const exactCount = zones.size;
  const canonical = new Map(rows('zone1970.tab').map(row => [row[2], row[0].split(',')]));
  const aliases = new Map();
  for (const line of inputs.backward.split(/\r?\n/)) {
    const parts = line.trim().split(/\s+/);
    if (parts.length >= 3 && parts[0] === 'Link') aliases.set(parts[2], parts[1]);
  }
  for (const [alias, initialTarget] of aliases) {
    if (zones.has(alias) || !alias.includes('/') || alias.startsWith('Etc/') || alias.startsWith('SystemV/')) continue;
    let target = initialTarget;
    const visited = new Set([alias]);
    while (aliases.has(target) && !visited.has(target)) {
      visited.add(target);
      target = aliases.get(target);
    }
    if (visited.has(target)) throw new Error(`Cyclic IANA alias: ${alias}`);
    const candidates = canonical.get(target) || [];
    if (candidates.length === 1) zones.set(alias, candidates[0]);
  }
  const countries = rows('iso3166.tab').map(row => row[0]);
  const countrySet = new Set(countries);
  for (const [name, country] of zones) {
    if (!countrySet.has(country)) throw new Error(`Unknown country for ${name}: ${country}`);
  }
  if (exactCount !== manifest.exactZoneCountryRows || zones.size !== manifest.generatedMappings || countries.length !== manifest.isoCountryCodes) {
    throw new Error('Generated counts differ from preserved snapshot metadata');
  }
  const sorted = Object.fromEntries([...zones.entries()].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
  const header = `// Generated from IANA tzdb ${version}: zone.tab, zone1970.tab, backward and iso3166.tab.\n` +
    '// https://data.iana.org/time-zones/tzdb/ — source data is public domain.\n' +
    '// Original country-specific names take precedence over clock-equivalent aliases.\n' +
    '// Additional aliases are admitted only when the canonical zone has one country.\n';
  const generated = header + `export const TIMEZONE_COUNTRIES = Object.freeze(${JSON.stringify(sorted, null, 2)});\n\n` +
    `export const ISO_COUNTRIES = new Set(${JSON.stringify(countries)});\n`;
  if (check) {
    if (await readFile(output, 'utf8') !== generated) throw new Error(`Generated map differs from ${output}`);
    console.log(`OK: byte-identical IANA ${version} map (${zones.size} timezone names, ${countries.length} country codes).`);
  } else {
    await writeFile(output, generated, 'utf8');
    console.log(`Wrote ${output} (${zones.size} timezone names, ${countries.length} country codes).`);
  }
}

try { await main(); }
catch (error) { console.error(`Timezone build failed: ${error.message}`); process.exitCode = 1; }
